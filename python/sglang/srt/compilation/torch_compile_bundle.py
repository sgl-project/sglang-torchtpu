"""Save and load PyTorch compiler cache bundles."""

from __future__ import annotations

import functools
import itertools
import logging
import os
import tempfile
from collections.abc import Callable
from pathlib import Path
from typing import Any

import torch
from torch._dynamo.source import (
    AttrSource,
    DefaultsSource,
    GlobalSource,
    LocalSource,
)
from torch._guards import ChainedSource

logger = logging.getLogger(__name__)


def save(path: Path) -> None:
    """Save all torch.compile artifacts in a bundle.

    This includes Dynamo guards and generated bytecode, which PyTorch normally
    does not cache because caching them reduces safety.
    """

    if path.exists():
        raise FileExistsError(f"torch.compile bundle exists: {path}")

    # PyTorch only flushes cached Dynamo bytecode in precompile mode.
    with torch._dynamo.config.patch(caching_precompile=True):
        result = torch.compiler.save_cache_artifacts()
    if result is None:
        raise RuntimeError("PyTorch produced no compiler artifacts during warmup.")
    serialized, cache_info = result

    from torch._inductor.codecache import write_atomic

    write_atomic(str(path), serialized, make_dirs=True)
    logger.info(
        "Saved torch.compile cache bundle %s (%d bytes, cache_info=%s).",
        path,
        len(serialized),
        cache_info,
    )


def load(path: Path) -> None:
    """Load torch.compile artifacts from a trusted bundle.

    Compiler artifacts use pickle internally and may execute arbitrary code.
    """

    if not path.is_file():
        raise FileNotFoundError(
            f"torch.compile cache bundle does not exist: {path}. Run once with "
            "--unsafe-save-torch-compile-bundle using the same directory and "
            "configuration."
        )
    serialized = path.read_bytes()
    _install_guards_state_loader()
    if torch.compiler.load_cache_artifacts(serialized) is None:
        raise RuntimeError(f"torch.compile cache bundle is invalid: {path}")
    logger.info(
        "Loaded torch.compile cache bundle %s (%d bytes).",
        path,
        len(serialized),
    )


_guards_state_loader_installed = False


def _install_guards_state_loader() -> None:
    """Drop the dict key-order records a bundle cannot evaluate on load and
    keep Dynamo's unique-id counter ahead of restored builtins-dict globals.

    Dynamo records the dicts whose key order a graph relies on (an enum-keyed
    dict read in the forward, such as a layer boundary's ``plan.paths``) next
    to the guards, and evaluates every record while rebuilding the guard
    manager. The guard filter never sees them, and one reached through the
    compiled wrapper's closure or a transient ``___unnamed_scope`` global
    dereferences a placeholder or missing global on load. Those dicts are built
    by the same code that wrote the bundle, so the record adds nothing here.

    In addition, ``CompilePackage.install()`` writes each entry's
    ``name_of_builtins_dict_key_in_fglobals`` (e.g. ``__builtins_dict___0``)
    into ``runtime_global_scope`` without advancing
    ``bytecode_transformation._unique_id_counter``. Advancing the counter past
    the restored suffix prevents a later Dynamo compile in the same process
    from minting a colliding ``__builtins_dict___<N>`` key.
    """
    global _guards_state_loader_installed
    if _guards_state_loader_installed:
        return
    _guards_state_loader_installed = True
    from torch._dynamo import bytecode_transformation, package

    orig_load_guards_state = package.load_guards_state

    def load_guards_state(guards_state: bytes) -> Any:
        state = orig_load_guards_state(guards_state)
        output_graph = state.output_graph
        kept = {
            source
            for source in output_graph.guard_on_key_order
            if not _rooted_in_transient_fn(source)
        }
        if len(kept) != len(output_graph.guard_on_key_order):
            object.__setattr__(output_graph, "guard_on_key_order", kept)
        builtin_key = getattr(
            output_graph, "name_of_builtins_dict_key_in_fglobals", None
        )
        if isinstance(builtin_key, str):
            _, _, suffix = builtin_key.rpartition("_")
            if suffix.isdigit():
                target_id = int(suffix)
                cur_id = next(bytecode_transformation._unique_id_counter)
                bytecode_transformation._unique_id_counter = itertools.count(
                    max(cur_id, target_id + 1)
                )
        return state

    package.load_guards_state = load_guards_state


def _source_chain(source: Any) -> tuple[Any, list[Any]]:
    """Return (root, chained sources from the root outwards)."""
    chain = []
    while isinstance(source, ChainedSource):
        chain.append(source)
        source = source.base
    chain.reverse()
    return source, chain


def _rooted_in_transient_fn(source: Any) -> bool:
    root, _ = _source_chain(source)
    return (isinstance(root, LocalSource) and root.local_name == "fn") or (
        isinstance(root, GlobalSource)
        and root.global_name.startswith("___unnamed_scope")
    )


def set_fresh_compiler_cache() -> tempfile.TemporaryDirectory[str]:
    """Route this process's compiler caches to a fresh temporary directory.

    Keep the returned directory alive while compiled functions may run.
    """

    cache_dir = tempfile.TemporaryDirectory(prefix="sglang-torch-compile-")
    os.environ["TORCHINDUCTOR_CACHE_DIR"] = cache_dir.name

    from torch._dynamo import package
    from torch._inductor.utils import clear_caches

    clear_caches()
    # Dynamo creates this singleton before the environment change above.
    package.DynamoCache = package.DiskDynamoCache(
        os.path.join(cache_dir.name, "dynamo")
    )
    return cache_dir


class Compiler:
    """Compile a function with cacheable Dynamo guards.

    caching_precompile must also cover calls because torch.compile is lazy.
    """

    def __init__(
        self,
        fn: Callable[..., Any],
        *,
        backend: Any,
        fullgraph: bool,
        dynamic: bool,
    ) -> None:
        with torch._dynamo.config.patch(caching_precompile=True):
            self.compiled = torch.compile(
                fn,
                backend=backend,
                fullgraph=fullgraph,
                dynamic=dynamic,
                options={"guard_filter_fn": _skip_unrestorable_guards_unsafe},
            )
        functools.update_wrapper(self, fn)

    def __call__(self, *args: Any, **kwargs: Any) -> Any:
        with torch._dynamo.config.patch(caching_precompile=True):
            return self.compiled(*args, **kwargs)


def _skip_unrestorable_guards_unsafe(guard_entries: Any) -> list[bool]:
    """Drop guards rooted in transient wrapper, forward-context, or unnamed
    scope state, and guards on a function's default arguments.

    A DefaultsSource guard cannot be restored from a bundle: torch's
    ``dataclass_with_cached_hash.__reduce__`` hands the source's ``init=False``
    fields to ``__init__`` on unpickle. A default argument is a code constant,
    so the guard adds nothing a same-code bundle needs.

    In ``torch>=2.13``, Dynamo traces ``NamedTuple.__new__`` (whose synthetic
    ``__globals__`` has ``__name__ == 'namedtuple_<Type>'``) and installs the
    frame globals as ``___unnamed_scope_<id>_c<compile_id>`` with a guard on
    that ``GlobalSource``. ``CompilePackage.install()`` does not restore
    ``___unnamed_scope_*`` globals into ``runtime_global_scope``, so keeping
    the guard causes a guaranteed guard miss on load.
    """

    forward_context_global = (
        "__import_sglang_dot_srt_dot_model_executor_dot_forward_context"
    )
    runtime_context_global = "__import_sglang_dot_srt_dot_runtime_context"
    keep = []
    for entry in guard_entries:
        source, chain = _source_chain(entry.orig_guard.originating_source)

        transient_fn = isinstance(source, LocalSource) and source.local_name == "fn"
        transient_unnamed_scope = isinstance(
            source, GlobalSource
        ) and source.global_name.startswith("___unnamed_scope")
        transient_forward_context = (
            isinstance(source, GlobalSource)
            and source.global_name == forward_context_global
            and any(
                isinstance(chained_source, AttrSource)
                and chained_source.member == "_current"
                for chained_source in chain
            )
        )
        # The same transient state read through _CONTEXT.forward; its ``scoped``
        # closure pickles as a placeholder the load-side guard dereferences.
        attrs = [
            chained_source.member
            for chained_source in chain
            if isinstance(chained_source, AttrSource)
        ]
        transient_runtime_forward = (
            isinstance(source, GlobalSource)
            and source.global_name == runtime_context_global
            and attrs[:2] == ["_CONTEXT", "forward"]
        )
        defaults_guard = any(
            isinstance(chained_source, DefaultsSource) for chained_source in chain
        )
        keep.append(
            not (
                transient_fn
                or transient_unnamed_scope
                or transient_forward_context
                or transient_runtime_forward
                or defaults_guard
            )
        )
    return keep
